import { test, expect, type Page } from '@playwright/test'
import { entrar, iniciarSedeNueva } from './helpers/sede'

test.skip(process.env.ESTABLECIMIENTO_E2E !== '1', 'Crea un negocio, consumos y cobros. Solo en una BD de prueba desechable.')

test('la primera venta desde los paneles del gerente, su mesero y su cajera', async ({ page, browser }) => {
  const { id, clave } = await iniciarSedeNueva(page)
  const boton = (p: Page, name: string) => p.getByRole('button', { name, exact: true })
  const ir = (name: string) => boton(page, name).click()
  const correo = (rol: string) => `${rol}-${id}@example.test`
  await ir('Personal')
  for (const [rol, nombre] of [['MESERO', 'Luis'], ['CAJERO', 'Eva']]) {
    await page.getByLabel('Nombre', { exact: true }).fill(nombre)
    await page.getByLabel('Apellido').fill('Rojas')
    await page.getByLabel('Email').fill(correo(rol))
    await page.getByLabel('Rol', { exact: true }).selectOption({ label: rol })
    await page.getByLabel('Contraseña', { exact: true }).fill(clave)
    await ir('Crear Personal')
    await expect(page.getByRole('row').filter({ hasText: correo(rol).toLowerCase() })).toContainText(rol)
  }
  await ir('Menú'); await ir('Administrar mesas')
  await page.getByLabel('Número de mesa').fill('1')
  await page.getByLabel('Capacidad').fill('4')
  await ir('Agregar mesa')
  const retirar = boton(page, 'Eliminar mesa 1')
  const confirmar = page.getByRole('dialog', { name: '¿Eliminar la mesa 1?' })
  await retirar.click(); await confirmar.getByRole('button', { name: 'Cancelar' }).click()
  await expect(page.getByRole('row').filter({ hasText: 'T-01' })).toContainText('4 personas')

  await ir('Inventario'); await ir('+ Nuevo Ingrediente')
  await page.getByLabel('Nombre', { exact: true }).fill('Masa')
  await page.getByLabel('Unidad de medida').fill('kg')
  await page.getByLabel('Stock mínimo').fill('9.5')
  await ir('Crear')
  const inv = page.getByRole('dialog', { name: 'Movimientos de Masa' })
  await ir('Movimientos')
  await inv.getByLabel('Cantidad (kg)').fill('9.6')
  await inv.getByLabel('Motivo').fill('Conteo inicial')
  await ir('Registrar movimiento')
  await expect(inv).toContainText('Stock actual: 9.6 kg')
  await ir('Cerrar ventana')
  const filaMasa = page.getByRole('row').filter({ hasText: 'Masa' })
  await filaMasa.getByRole('button', { name: 'Editar' }).click()
  const editor = page.getByRole('dialog', { name: 'Editar Ingrediente' })
  await expect(editor.getByLabel('Stock mínimo')).toHaveValue('9.5')
  await expect(editor.getByLabel('Stock actual')).toHaveValue('9.6')
  await editor.getByLabel('Stock actual').fill('10')
  await editor.getByLabel('Motivo del ajuste').fill('Recuento de la bodega')
  await editor.getByRole('button', { name: 'Actualizar' }).click()
  await expect(filaMasa.getByRole('cell', { name: '10', exact: true })).toBeVisible()
  await page.reload(); await ir('Inventario')
  await filaMasa.getByRole('button', { name: 'Editar' }).click()
  await expect(editor.getByLabel('Stock actual')).toHaveValue('10')
  await ir('Cancelar'); await ir('Movimientos')
  await expect(inv).toContainText('Stock actual: 10 kg')
  await expect(inv.getByRole('listitem').filter({ hasText: 'Recuento de la bodega' })).toContainText('Entrada: 0.4 kg')
  await ir('Cerrar ventana')
  await ir('Menú'); await ir('+ Nuevo Producto')
  await page.getByLabel('Nombre', { exact: true }).fill('Arepa')
  await page.getByLabel('Precio', { exact: true }).fill('10000')
  await ir('Crear'); await ir('Receta')
  const receta = page.getByRole('dialog', { name: 'Receta de Arepa' })
  await receta.getByLabel('Masa (kg)').fill('0.25')
  await ir('Guardar receta'); await expect(receta).toHaveCount(0)
  await ir('Flujo de Caja'); await ir('+ Nueva Caja')
  await page.getByLabel('Nombre de la caja').fill('Mostrador')
  await ir('Crear')
  await expect(page.getByRole('cell', { name: 'Mostrador' })).toBeVisible()
  await ir('Turnos'); await ir('Abrir turno')
  await page.getByLabel('Caja', { exact: true }).selectOption({ label: 'Mostrador' })
  await page.getByLabel('Cajero', { exact: true }).selectOption({ label: 'Eva Rojas' })
  await page.getByPlaceholder('Efectivo inicial').fill('50000')
  await ir('Confirmar apertura'); await expect(boton(page, 'Cerrar turno')).toBeVisible()
  await ir('Mesas'); await retirar.click() // Confirmación abierta mientras otro usuario ocupa la mesa.

  const salon = await browser.newPage(), caja = await browser.newPage()
  try {
    await entrar(salon, correo('MESERO'), clave)
    await boton(salon, 'Mesa 01, Disponible. Ver mesa').click()
    const ficha = salon.getByRole('dialog', { name: 'Mesa 01' })
    await ficha.getByLabel('Comensales a sentar').fill('2')
    await boton(salon, 'Tomar pedido').click()
    await boton(salon, 'Agregar Arepa').click(); await boton(salon, 'Sumar Arepa').click()
    await boton(salon, 'Enviar a cocina').click()
    await expect(ficha.getByText('2 × Arepa')).toBeVisible()
    await confirmar.getByRole('button', { name: 'Eliminar mesa' }).click()
    await expect(page.getByRole('alert')).toContainText('cuenta abierta')
    await expect(retirar).toBeDisabled()
    await ir('Inventario'); await ir('Movimientos')
    await expect(inv).toContainText('Stock actual: 9.5 kg')
    await expect(inv.getByRole('listitem')).toHaveCount(3) // Entrada inicial, diferencia del conteo y consumo.
    await expect(inv.getByRole('listitem').filter({ hasText: 'Salida: 0.5 kg' })).toHaveCount(1)
    await ir('Cerrar ventana')

    await boton(salon, 'Cerrar ventana').click()
    await salon.getByRole('link', { name: 'Cocina', exact: true }).click()
    const plato = salon.getByRole('article').filter({ hasText: 'Arepa' })
    await plato.getByRole('button', { name: 'Empezar' }).click()
    await plato.getByRole('button', { name: 'Marcar listo' }).click()
    await salon.getByRole('link', { name: 'Volver al salón' }).click()
    await boton(salon, 'Mesa 01, Ocupada. Ver mesa').click()
    await boton(salon, 'Marcar servido').click()
    await boton(salon, 'Enviar a caja').click(); await boton(salon, 'Confirmar').click()
    await expect(ficha).toContainText('Cuenta en caja')

    await entrar(caja, correo('CAJERO'), clave)
    await caja.getByRole('button', { name: /Pedido #\d+ ·/ }).click()
    await caja.getByRole('button', { name: /Transferencia/i }).click()
    await caja.getByRole('button', { name: /Cerrar cuenta y facturar/ }).click()
    const comprobante = caja.locator('#comprobante')
    await expect(comprobante).toContainText('Arepa')
    await expect(comprobante.locator('.cajero__total-final')).toContainText('23.800')
    await expect(comprobante).toContainText('TRANSFERENCIA')

    await ir('Finanzas')
    await expect(page.getByRole('row').filter({ hasText: 'Pago Transferencia' })).toContainText('23.800')
    await ir('Turnos'); await ir('Cerrar turno')
    await page.getByLabel('Efectivo contado').fill('50000')
    await ir('Confirmar cierre')
    await expect(page.getByRole('row').filter({ hasText: 'Eva Rojas' })).toContainText(/Esperado\s*\$\s*50\.000\s*·\s*Diferencia\s*\$\s*0/)
    await ir('Inventario'); await ir('Movimientos')
    await expect(inv).toContainText('Stock actual: 9.5 kg')
    await expect(inv.getByRole('listitem')).toHaveCount(3) // Cobrar no crea otra salida.
    await ir('Cerrar ventana'); await ir('Mesas')
    await retirar.click(); await confirmar.getByRole('button', { name: 'Eliminar mesa' }).click()
    await expect(page.getByText('No hay mesas registradas para este establecimiento.')).toBeVisible()
    await ir('Menú')
    await expect(page.getByRole('article').filter({ hasText: 'Ingresos del día' })).toContainText('23.800')
    await expect(page.getByText('Mesa 01 - Pago recibido')).toBeVisible()
    await expect(page.getByText('Stock 9.5 kg · mínimo 9.5 kg')).toBeVisible()
    await ir('Ver finanzas')
    await expect(page.getByRole('row').filter({ hasText: 'Pago Transferencia' })).toContainText('23.800')
  } finally { await salon.close(); await caja.close() }
})
